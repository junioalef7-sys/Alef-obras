    raise exception 'Acesso indisponível. Regularize sua assinatura para usar Compras.';
  end if;
  perform public.cancelar_compra_interno(p_compra_id,p_motivo);
end;
$function$;
CREATE OR REPLACE FUNCTION public.cancelar_compra_interno(p_compra_id uuid, p_motivo text DEFAULT NULL::text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_empresa_id uuid;
  v_compra public.compras%rowtype;
  v_saldo numeric(14,3);
  r record;
begin

  select empresa_id
  into v_empresa_id
  from public.perfis
  where id = auth.uid();

  if v_empresa_id is null then
    raise exception 'Usuário sem empresa vinculada.';
  end if;


  select *
  into v_compra
  from public.compras
  where id = p_compra_id
    and empresa_id = v_empresa_id
  for update;

  if not found then
    raise exception 'Compra não encontrada ou sem permissão.';
  end if;


  if v_compra.cancelamento_processado then
    return;
  end if;


  -- ===================================================
  -- ESTORNO DO ESTOQUE
  -- ===================================================

  if v_compra.estoque_processado then

    for r in
      select *
      from public.estoque_movimentacoes
      where compra_id = v_compra.id
        and empresa_id = v_empresa_id
        and tipo = 'entrada'
    loop

      -- Evita estornar duas vezes
      if not exists (
        select 1
        from public.estoque_movimentacoes
        where estorno_de_id = r.id
      ) then

        select quantidade
        into v_saldo
        from public.estoque_saldos
        where estoque_id = r.estoque_destino_id
          and material_id = r.material_id
        for update;


        if coalesce(v_saldo, 0) < r.quantidade then
          raise exception
            'Não é possível cancelar: parte do material da compra já saiu do estoque.';
        end if;


        update public.estoque_saldos
        set
          quantidade = quantidade - r.quantidade,
          atualizado_em = now()
        where estoque_id = r.estoque_destino_id
          and material_id = r.material_id;


        insert into public.estoque_movimentacoes (
          empresa_id,
          material_id,
          estoque_origem_id,
          obra_id,
          compra_id,
          tipo,
          quantidade,
          custo_unitario,
          valor_total,
          data,
          documento,
          observacoes,
          estorno_de_id
        )
        values (
          v_empresa_id,
          r.material_id,
          r.estoque_destino_id,
          v_compra.obra_id,
          v_compra.id,
          'saida',
          r.quantidade,
          r.custo_unitario,
          r.valor_total,
          current_date,
          coalesce(
            v_compra.nota_fiscal,
            v_compra.numero_documento
          ),
          'Estorno automático por cancelamento da compra',
          r.id
        );

      end if;

    end loop;

  end if;


  -- ===================================================
  -- ESTORNO FINANCEIRO
  -- Mantém o lançamento para auditoria
  -- ===================================================

  if v_compra.financeiro_processado then

    update public.financeiro
    set
      status_lancamento = 'estornado',
      atualizado_em = now(),
      observacoes =
        concat_ws(
          ' | ',
          observacoes,
          'Estornado por cancelamento da compra'
        )
    where compra_id = v_compra.id
      and empresa_id = v_empresa_id
      and origem = 'compra';

  end if;


  -- ===================================================
  -- FINALIZA CANCELAMENTO
  -- ===================================================

  update public.compras
  set
    status = 'cancelada',
    cancelamento_processado = true,
    cancelada_em = now(),
    motivo_cancelamento = p_motivo,
    atualizado_em = now()
  where id = v_compra.id;

end;
$function$;
CREATE OR REPLACE FUNCTION public.handle_new_obrix_user()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_empresa_id uuid;
  v_nome text;
  v_empresa_nome text;
begin
  v_nome := nullif(trim(coalesce(
    new.raw_user_meta_data ->> 'nome',
    new.raw_user_meta_data ->> 'full_name',
    ''
  )), '');

  if v_nome is null then
    v_nome := coalesce(new.email, 'Usuário');
  end if;

  v_empresa_nome := nullif(trim(coalesce(
    new.raw_user_meta_data ->> 'empresa_nome',
    new.raw_user_meta_data ->> 'company_name',
    ''
  )), '');

  if v_empresa_nome is null then
    v_empresa_nome := v_nome;
  end if;

  insert into public.empresas (nome)
  values (v_empresa_nome)
  returning id into v_empresa_id;

  insert into public.perfis (
    id,
    empresa_id,
    nome,
    email,
    papel
  )
  values (
    new.id,
    v_empresa_id,
    v_nome,
    new.email,
    'proprietario'
  );

  insert into public.assinaturas (
    empresa_id,
    plano,
    status,
    trial_inicio,
    trial_fim
  )
  values (
    v_empresa_id,
    'teste',
    'teste',
    now(),
    now() + interval '7 days'
  );

  return new;
end;
