CREATE OR REPLACE FUNCTION public.obrix_ajustar_estoque(p_material_id uuid, p_estoque_id uuid, p_quantidade_real numeric, p_data date DEFAULT CURRENT_DATE, p_documento text DEFAULT NULL::text, p_observacoes text DEFAULT NULL::text)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_empresa_id uuid := public.obrix_empresa_atual();
  v_obra_id uuid;
  v_unidade text;
  v_saldo numeric := 0;
  v_diferenca numeric;
  v_custo numeric := 0;
  v_movimento_id uuid;
begin
  if (select auth.uid()) is null then
    raise exception 'Usuário não autenticado.';
  end if;
  if v_empresa_id is null then
    raise exception 'Empresa atual não encontrada.';
  end if;
  if not public.obrix_acesso_total(v_empresa_id) then
    raise exception 'Acesso não autorizado para esta empresa.';
  end if;
  if p_quantidade_real is null or p_quantidade_real < 0 then
    raise exception 'A quantidade real deve ser zero ou maior.';
  end if;

  select unidade, coalesce(custo_medio,0)
    into v_unidade, v_custo
    from public.materiais
   where id = p_material_id
     and empresa_id = v_empresa_id
     and ativo = true;
  if not found then
    raise exception 'Material ativo não encontrado.';
  end if;

  if lower(coalesce(v_unidade,'')) in ('un','unidade','unidades','saco','sacos','cx','caixa','caixas')
     and p_quantidade_real <> trunc(p_quantidade_real) then
    raise exception 'Este material só aceita quantidade inteira.';
  end if;

  select obra_id
    into v_obra_id
    from public.estoques
   where id = p_estoque_id
     and empresa_id = v_empresa_id
     and ativo = true;
  if not found then
    raise exception 'Local de estoque ativo não encontrado.';
  end if;

  select quantidade
    into v_saldo
    from public.estoque_saldos
   where empresa_id = v_empresa_id
     and estoque_id = p_estoque_id
     and material_id = p_material_id
   for update;
  if not found then
    v_saldo := 0;
  end if;

  v_diferenca := p_quantidade_real - v_saldo;
  if v_diferenca = 0 then
    return null;
  end if;

  insert into public.estoque_saldos(empresa_id, estoque_id, material_id, quantidade, atualizado_em)
  values(v_empresa_id, p_estoque_id, p_material_id, p_quantidade_real, now())
  on conflict (estoque_id, material_id)
  do update set quantidade = excluded.quantidade,
                atualizado_em = now();

  insert into public.estoque_movimentacoes(
    empresa_id, material_id, estoque_origem_id, estoque_destino_id, obra_id, tipo,
    quantidade, custo_unitario, valor_total, data, documento, observacoes
  ) values (
    v_empresa_id,
    p_material_id,
    case when v_diferenca < 0 then p_estoque_id else null end,
    case when v_diferenca > 0 then p_estoque_id else null end,
    v_obra_id,
    'ajuste',
    abs(v_diferenca),
    v_custo,
    abs(v_diferenca) * v_custo,
    coalesce(p_data,current_date),
    nullif(trim(p_documento),''),
    concat('Ajuste de inventário: saldo anterior ', v_saldo, ', saldo real ', p_quantidade_real,
           case when nullif(trim(p_observacoes),'') is not null then '. ' || trim(p_observacoes) else '' end)
  ) returning id into v_movimento_id;

  return v_movimento_id;
end;
$function$;
CREATE OR REPLACE FUNCTION public.obrix_aplicar_pagamento_assinatura(p_pagamento_id uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_pag public.pagamentos_assinatura%rowtype;
  v_ass public.assinaturas%rowtype;
  v_base timestamptz;
  v_inicio timestamptz;
  v_fim timestamptz;
begin
  select * into v_pag
  from public.pagamentos_assinatura
  where id = p_pagamento_id
  for update;

  if not found then
    raise exception 'Pagamento não encontrado.';
  end if;

  if v_pag.aplicado_em is not null and v_pag.revertido_em is null then
    return jsonb_build_object(
      'ok', true,
      'ja_aplicado', true,
      'pagamento_id', v_pag.id,
      'periodo_concedido_inicio', v_pag.periodo_concedido_inicio,
      'periodo_concedido_fim', v_pag.periodo_concedido_fim
    );
  end if;

  if v_pag.status <> 'aprovado' then
    raise exception 'Pagamento ainda não foi confirmado pelo provedor.';
  end if;

  select * into v_ass
  from public.assinaturas
  where id = v_pag.assinatura_id
    and empresa_id = v_pag.empresa_id
  for update;

  if not found then
    raise exception 'Assinatura não encontrada para este pagamento.';
  end if;

  -- Evita downgrade da assinatura permanente na confirmação de pagamentos antigos.
  if v_ass.plano = 'permanente' and v_ass.status = 'ativo' then
    update public.pagamentos_assinatura
       set aplicado_em = now(),
           aprovado_em = coalesce(aprovado_em, now()),
           periodo_concedido_inicio = null,
           periodo_concedido_fim = null,
           revertido_em = null
     where id = v_pag.id;
    return jsonb_build_object('ok', true, 'acesso_permanente', true,
                              'pagamento_id', v_pag.id, 'empresa_id', v_pag.empresa_id);
  end if;

  if v_ass.status = 'ativo'
     and v_ass.periodo_fim is not null
     and v_ass.periodo_fim > now() then
    v_base := v_ass.periodo_fim;
    v_inicio := coalesce(v_ass.periodo_inicio, now());
  elsif v_ass.status = 'teste' and v_ass.trial_fim > now() then
    v_base := v_ass.trial_fim;
    v_inicio := v_ass.trial_fim;
  else
    v_base := now();
    v_inicio := now();
  end if;

  if v_pag.plano = 'anual' then
    v_fim := v_base + interval '1 year';
  else
    v_fim := v_base + interval '1 month';
  end if;

  update public.assinaturas
  set plano = v_pag.plano,
      status = 'ativo',
      periodo_inicio = v_inicio,
      periodo_fim = v_fim,
      provedor_pagamento = v_pag.provedor,
      atualizado_em = now()
  where id = v_ass.id;

  update public.pagamentos_assinatura
  set aplicado_em = now(),
      aprovado_em = coalesce(aprovado_em, now()),
      periodo_concedido_inicio = v_base,
      periodo_concedido_fim = v_fim,
      revertido_em = null
  where id = v_pag.id;

  return jsonb_build_object(
    'ok', true,
    'ja_aplicado', false,
    'pagamento_id', v_pag.id,
    'empresa_id', v_pag.empresa_id,
    'plano', v_pag.plano,
    'periodo_inicio', v_inicio,
    'periodo_fim', v_fim,
    'periodo_concedido_inicio', v_base,
    'periodo_concedido_fim', v_fim
  );
end;
$function$;
