CREATE OR REPLACE FUNCTION public.obrix_reverter_pagamento_assinatura(p_pagamento_id uuid, p_motivo text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_pag public.pagamentos_assinatura%rowtype;
  v_ass public.assinaturas%rowtype;
  v_novo_fim timestamptz;
  v_outros_validos integer := 0;
  v_agora timestamptz := now();
begin
  select * into v_pag
  from public.pagamentos_assinatura
  where id = p_pagamento_id
  for update;

  if not found then
    raise exception 'Pagamento não encontrado.';
  end if;

  if v_pag.aplicado_em is null then
    return jsonb_build_object('ok', true, 'sem_periodo_aplicado', true, 'pagamento_id', v_pag.id);
  end if;

  if v_pag.revertido_em is not null then
    return jsonb_build_object('ok', true, 'ja_revertido', true, 'pagamento_id', v_pag.id, 'revertido_em', v_pag.revertido_em);
  end if;

  select * into v_ass
  from public.assinaturas
  where id = v_pag.assinatura_id
    and empresa_id = v_pag.empresa_id
  for update;

  if not found then
    raise exception 'Assinatura não encontrada para este pagamento.';
  end if;

  select count(*)::int into v_outros_validos
  from public.pagamentos_assinatura p
  where p.assinatura_id = v_pag.assinatura_id
    and p.id <> v_pag.id
    and p.aplicado_em is not null
    and p.revertido_em is null
    and p.status = 'aprovado';

  if v_ass.periodo_fim is not null then
    if v_pag.plano = 'anual' then
      v_novo_fim := v_ass.periodo_fim - interval '1 year';
    else
      v_novo_fim := v_ass.periodo_fim - interval '1 month';
    end if;
  end if;

  update public.pagamentos_assinatura
  set revertido_em = v_agora,
      detalhes = coalesce(detalhes, '{}'::jsonb) || jsonb_build_object(
        'reversao_assinatura', jsonb_build_object(
          'em', v_agora,
          'motivo', nullif(trim(coalesce(p_motivo, '')), '')
        )
      )
  where id = v_pag.id;

  -- Estorno de cobrança passada não cancela o direito permanente.
  if v_ass.plano = 'permanente' and v_ass.status = 'ativo' then
    return jsonb_build_object('ok', true, 'acesso_permanente', true,
                              'pagamento_id', v_pag.id, 'novo_periodo_fim', null);
  end if;

  if v_outros_validos > 0 then
    update public.assinaturas
    set periodo_fim = case
          when v_novo_fim is null then periodo_fim
          when periodo_inicio is not null and v_novo_fim < periodo_inicio then periodo_inicio
          else v_novo_fim
        end,
        status = 'ativo',
        atualizado_em = v_agora
    where id = v_ass.id;
  elsif v_ass.trial_fim is not null and v_agora < v_ass.trial_fim then
    update public.assinaturas
    set plano = 'teste',
        status = 'teste',
        periodo_inicio = null,
        periodo_fim = null,
        provedor_pagamento = null,
        atualizado_em = v_agora
    where id = v_ass.id;
  else
    update public.assinaturas
    set status = 'cancelado',
        periodo_inicio = null,
        periodo_fim = null,
        provedor_pagamento = null,
        atualizado_em = v_agora
    where id = v_ass.id;
  end if;

  return jsonb_build_object(
    'ok', true,
    'ja_revertido', false,
    'pagamento_id', v_pag.id,
    'outros_pagamentos_validos', v_outros_validos,
    'trial_ainda_valido', (v_ass.trial_fim is not null and v_agora < v_ass.trial_fim),
    'novo_periodo_fim', v_novo_fim
  );
end;
$function$;
CREATE OR REPLACE FUNCTION public.obrix_signup_rate_limit(p_chave text, p_limite integer, p_janela_segundos integer)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_agora timestamptz := now();
  v_inicio timestamptz;
  v_tentativas integer;
begin
  if p_chave is null or length(trim(p_chave)) < 8 then
    raise exception 'Chave de rate limit inválida.';
  end if;
  if p_limite is null or p_limite < 1 or p_limite > 1000 then
    raise exception 'Limite inválido.';
  end if;
  if p_janela_segundos is null or p_janela_segundos < 10 or p_janela_segundos > 86400 then
    raise exception 'Janela inválida.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext(p_chave));

  select janela_inicio, tentativas
    into v_inicio, v_tentativas
  from private.obrix_signup_rate_limits
  where chave = p_chave
  for update;

  if not found or v_inicio + pg_catalog.make_interval(secs => p_janela_segundos) <= v_agora then
    insert into private.obrix_signup_rate_limits(chave, janela_inicio, tentativas, atualizado_em)
    values (p_chave, v_agora, 1, v_agora)
    on conflict (chave) do update
      set janela_inicio = excluded.janela_inicio,
          tentativas = 1,
          atualizado_em = excluded.atualizado_em;
    return true;
  end if;

  if v_tentativas >= p_limite then
    update private.obrix_signup_rate_limits
       set atualizado_em = v_agora
     where chave = p_chave;
    return false;
  end if;

  update private.obrix_signup_rate_limits
     set tentativas = tentativas + 1,
         atualizado_em = v_agora
   where chave = p_chave;

  return true;
end;
$function$;
CREATE OR REPLACE FUNCTION public.obrix_status_acesso()
 RETURNS jsonb
 LANGUAGE sql
