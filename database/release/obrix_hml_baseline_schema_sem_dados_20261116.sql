CREATE OR REPLACE FUNCTION public.obrix_pagar_compra(p_compra_id uuid, p_forma_pagamento text, p_data_pagamento date DEFAULT CURRENT_DATE, p_numero_documento text DEFAULT NULL::text)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_empresa_id uuid := public.obrix_empresa_atual();
  v_compra public.compras%rowtype;
  v_subtotal numeric(14,2);
  v_total numeric(14,2);
  v_financeiro_id uuid;
begin
  if (select auth.uid()) is null then
    raise exception 'Usuário não autenticado.';
  end if;
  if v_empresa_id is null then
    raise exception 'Empresa atual não encontrada.';
  end if;
  if not public.obrix_acesso_total(v_empresa_id) then
    raise exception 'Acesso não autorizado para esta empresa.';
  end if;

  select * into v_compra
    from public.compras
   where id = p_compra_id
     and empresa_id = v_empresa_id
   for update;
  if not found then
    raise exception 'Compra não encontrada.';
  end if;
  if v_compra.status = 'cancelada' then
    raise exception 'Compra cancelada não pode ser paga.';
  end if;
  if not v_compra.estoque_processado or v_compra.status not in ('recebida','paga') then
    raise exception 'A compra precisa ser recebida no estoque antes do pagamento.';
  end if;
  if v_compra.financeiro_processado or exists (
    select 1 from public.financeiro
     where compra_id = v_compra.id
       and empresa_id = v_empresa_id
       and status_lancamento = 'ativo'
  ) then
    raise exception 'Esta compra já foi lançada no Financeiro.';
  end if;
  if nullif(trim(coalesce(p_forma_pagamento,'')),'') is null then
    raise exception 'Informe a forma de pagamento.';
  end if;

  select coalesce(sum(valor_total),0)
    into v_subtotal
    from public.compra_itens
   where compra_id = v_compra.id
     and empresa_id = v_empresa_id;

  v_total := greatest(v_subtotal - v_compra.desconto + v_compra.frete + v_compra.outros_custos, 0);
  if v_total <= 0 then
    raise exception 'O valor total da compra precisa ser maior que zero para registrar o pagamento.';
  end if;

  update public.compras
     set subtotal = v_subtotal,
         valor_total = v_total,
         status = 'paga',
         forma_pagamento = trim(p_forma_pagamento),
         numero_documento = coalesce(nullif(trim(coalesce(p_numero_documento,'')),''), numero_documento),
         atualizado_em = now()
   where id = v_compra.id;

  insert into public.financeiro(
    empresa_id, obra_id, tipo, categoria, descricao, valor, data,
    origem, compra_id, observacoes, status_lancamento
  ) values (
    v_empresa_id,
    v_compra.obra_id,
    'despesa',
    'material',
    'Compra #' || v_compra.numero_pedido::text,
    v_total,
    coalesce(p_data_pagamento,current_date),
    'compra',
    v_compra.id,
    'Pagamento de compra · ' || trim(p_forma_pagamento),
    'ativo'
  ) returning id into v_financeiro_id;

  update public.compras
     set financeiro_processado = true,
         atualizado_em = now()
   where id = v_compra.id;

  return v_financeiro_id;
end;
$function$;
CREATE OR REPLACE FUNCTION public.obrix_pagar_diarias(p_funcionario_id uuid, p_diaria_ids uuid[])
 RETURNS uuid
 LANGUAGE plpgsql
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  v_empresa_id uuid;
  v_pagamento_id uuid;
  v_total numeric(14,2);
  v_qtd_ids integer;
  v_qtd_validas integer;
  v_funcionario_nome text;
begin
  v_empresa_id := public.obrix_empresa_atual();

  if v_empresa_id is null or not public.obrix_acesso_total(v_empresa_id) then
    raise exception 'Acesso não autorizado para pagamento de equipe';
  end if;

  if p_funcionario_id is null or p_diaria_ids is null or cardinality(p_diaria_ids) = 0 then
    raise exception 'Funcionário e ao menos uma diária são obrigatórios';
  end if;

  select nome
    into v_funcionario_nome
  from public.funcionarios
  where id = p_funcionario_id
    and empresa_id = v_empresa_id;

  if v_funcionario_nome is null then
    raise exception 'Funcionário não encontrado nesta empresa';
  end if;

  select count(*)
    into v_qtd_ids
  from (select distinct unnest(p_diaria_ids) as id) s;

  perform 1
  from public.diarias d
  where d.id = any(p_diaria_ids)
  order by d.id
  for update;

  select count(*), coalesce(sum(d.valor_total),0)
    into v_qtd_validas, v_total
  from public.diarias d
  join (select distinct unnest(p_diaria_ids) as id) s on s.id = d.id
  where d.empresa_id = v_empresa_id
    and d.funcionario_id = p_funcionario_id
    and d.paga = false;

  if v_qtd_validas <> v_qtd_ids then
    raise exception 'Há diária inválida, já paga ou pertencente a outro funcionário/empresa';
  end if;

  if v_total <= 0 then
    raise exception 'O total das diárias deve ser maior que zero';
  end if;

  insert into public.pagamentos_equipe (
    empresa_id, funcionario_id, valor_diarias, valor_bonus_extras,
    valor_vales, valor_bruto, valor_liquido, data_pagamento, observacoes
  ) values (
    v_empresa_id, p_funcionario_id, v_total, 0,
    0, v_total, v_total, current_date, 'Pagamento de diárias'
  )
  returning id into v_pagamento_id;

  insert into public.pagamento_diarias (
    empresa_id, pagamento_id, diaria_id, obra_id, valor
  )
  select d.empresa_id, v_pagamento_id, d.id, d.obra_id, d.valor_total
  from public.diarias d
  join (select distinct unnest(p_diaria_ids) as id) s on s.id = d.id;

  update public.diarias d
     set paga = true,
         pago_em = now()
  from (select distinct unnest(p_diaria_ids) as id) s
  where d.id = s.id;

  insert into public.financeiro (
    empresa_id, obra_id, tipo, categoria, descricao, valor, data,
    origem, pagamento_equipe_id, observacoes, status_lancamento
  )
  select
    v_empresa_id,
    d.obra_id,
    'despesa',
    'mao_de_obra',
    'Pagamento equipe - ' || v_funcionario_nome,
    sum(d.valor_total),
    current_date,
    'pagamento_equipe',
    v_pagamento_id,
    'Gerado automaticamente pelas diárias pagas na obra de origem',
    'ativo'
  from public.diarias d
  join (select distinct unnest(p_diaria_ids) as id) s on s.id = d.id
  group by d.obra_id
  having sum(d.valor_total) > 0;

  return v_pagamento_id;
end;
$function$;
CREATE OR REPLACE FUNCTION public.obrix_pagar_equipe_completo(p_funcionario_id uuid, p_diaria_ids uuid[] DEFAULT '{}'::uuid[], p_vale_ids uuid[] DEFAULT '{}'::uuid[], p_bonus_ids uuid[] DEFAULT '{}'::uuid[])
 RETURNS jsonb
 LANGUAGE plpgsql
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  v_empresa_id uuid;
  v_pagamento_id uuid;
  v_funcionario_nome text;
  v_diaria_ids uuid[] := coalesce(p_diaria_ids, '{}'::uuid[]);
  v_vale_ids uuid[] := coalesce(p_vale_ids, '{}'::uuid[]);
  v_bonus_ids uuid[] := coalesce(p_bonus_ids, '{}'::uuid[]);
  v_diarias numeric(14,2) := 0;
  v_vales numeric(14,2) := 0;
  v_bonus numeric(14,2) := 0;
  v_bruto numeric(14,2) := 0;
  v_liquido numeric(14,2) := 0;
  v_ids integer;
  v_validos integer;
begin
  v_empresa_id := public.obrix_empresa_atual();
  if v_empresa_id is null or not public.obrix_acesso_total(v_empresa_id) then
    raise exception 'Acesso não autorizado para pagamento de equipe';
  end if;

  if p_funcionario_id is null then
    raise exception 'Funcionário é obrigatório';
  end if;

  if cardinality(v_diaria_ids)=0 and cardinality(v_vale_ids)=0 and cardinality(v_bonus_ids)=0 then
    raise exception 'Selecione ao menos uma diária, vale ou bônus/extra';
  end if;

  select nome into v_funcionario_nome
  from public.funcionarios
  where id=p_funcionario_id and empresa_id=v_empresa_id;
  if v_funcionario_nome is null then
    raise exception 'Funcionário não encontrado nesta empresa';
  end if;

  if cardinality(v_diaria_ids)>0 then
    perform 1 from public.diarias where id=any(v_diaria_ids) order by id for update;
    select count(*) into v_ids from (select distinct unnest(v_diaria_ids) id) s;
    select count(*), coalesce(sum(d.valor_total),0) into v_validos,v_diarias
    from public.diarias d join (select distinct unnest(v_diaria_ids) id) s on s.id=d.id
    where d.empresa_id=v_empresa_id and d.funcionario_id=p_funcionario_id and d.paga=false;
    if v_validos<>v_ids then raise exception 'Há diária inválida, já paga ou de outro funcionário'; end if;
  end if;

  if cardinality(v_vale_ids)>0 then
    perform 1 from public.vales where id=any(v_vale_ids) order by id for update;
    select count(*) into v_ids from (select distinct unnest(v_vale_ids) id) s;
    select count(*), coalesce(sum(v.valor),0) into v_validos,v_vales
    from public.vales v join (select distinct unnest(v_vale_ids) id) s on s.id=v.id
    where v.empresa_id=v_empresa_id and v.funcionario_id=p_funcionario_id and v.quitado=false;
    if v_validos<>v_ids then raise exception 'Há vale inválido, já quitado ou de outro funcionário'; end if;
  end if;

  if cardinality(v_bonus_ids)>0 then
    perform 1 from public.bonus_extras where id=any(v_bonus_ids) order by id for update;
    select count(*) into v_ids from (select distinct unnest(v_bonus_ids) id) s;
    select count(*), coalesce(sum(b.valor),0) into v_validos,v_bonus
    from public.bonus_extras b join (select distinct unnest(v_bonus_ids) id) s on s.id=b.id
    where b.empresa_id=v_empresa_id and b.funcionario_id=p_funcionario_id and b.pago=false;
    if v_validos<>v_ids then raise exception 'Há bônus/extra inválido, já pago ou de outro funcionário'; end if;
    if exists (
      select 1 from public.bonus_extras b
      join (select distinct unnest(v_bonus_ids) id) s on s.id=b.id
      where b.obra_id is null
    ) then
      raise exception 'Bônus/extra selecionado precisa estar vinculado a uma obra';
    end if;
  end if;

  v_bruto := v_diarias + v_bonus;
  v_liquido := v_bruto - v_vales;

  if v_bruto<=0 then raise exception 'O valor bruto deve ser maior que zero'; end if;
  if v_liquido<0 then raise exception 'Os vales não podem ultrapassar o valor bruto deste pagamento'; end if;

  insert into public.pagamentos_equipe(
    empresa_id,funcionario_id,valor_diarias,valor_bonus_extras,valor_vales,
    valor_bruto,valor_liquido,data_pagamento,observacoes
  ) values (
    v_empresa_id,p_funcionario_id,v_diarias,v_bonus,v_vales,
    v_bruto,v_liquido,current_date,'Pagamento de equipe com diárias, vales e bônus/extras'
  ) returning id into v_pagamento_id;

  if cardinality(v_diaria_ids)>0 then
    insert into public.pagamento_diarias(empresa_id,pagamento_id,diaria_id,obra_id,valor)
    select d.empresa_id,v_pagamento_id,d.id,d.obra_id,d.valor_total
    from public.diarias d join (select distinct unnest(v_diaria_ids) id) s on s.id=d.id;

    update public.diarias d set paga=true,pago_em=now()
    from (select distinct unnest(v_diaria_ids) id) s where d.id=s.id;
  end if;

  if cardinality(v_vale_ids)>0 then
    insert into public.pagamento_vales(empresa_id,pagamento_id,vale_id,valor)
    select v.empresa_id,v_pagamento_id,v.id,v.valor
    from public.vales v join (select distinct unnest(v_vale_ids) id) s on s.id=v.id;

    update public.vales v set quitado=true,quitado_em=now()
    from (select distinct unnest(v_vale_ids) id) s where v.id=s.id;
  end if;

  if cardinality(v_bonus_ids)>0 then
    insert into public.pagamento_bonus_extras(empresa_id,pagamento_id,bonus_extra_id,valor)
    select b.empresa_id,v_pagamento_id,b.id,b.valor
    from public.bonus_extras b join (select distinct unnest(v_bonus_ids) id) s on s.id=b.id;

    update public.bonus_extras b set pago=true,pago_em=now()
    from (select distinct unnest(v_bonus_ids) id) s where b.id=s.id;
  end if;

  insert into public.financeiro(
    empresa_id,obra_id,tipo,categoria,descricao,valor,data,origem,
    pagamento_equipe_id,observacoes,status_lancamento
  )
  select v_empresa_id,t.obra_id,'despesa','mao_de_obra',
         'Pagamento equipe - '||v_funcionario_nome,
         sum(t.valor),current_date,'pagamento_equipe',v_pagamento_id,
         'Custo de mão de obra por obra; vales apenas reduzem o líquido a pagar','ativo'
  from (
    select d.obra_id,d.valor_total as valor
    from public.diarias d join (select distinct unnest(v_diaria_ids) id) s on s.id=d.id
    union all
    select b.obra_id,b.valor
    from public.bonus_extras b join (select distinct unnest(v_bonus_ids) id) s on s.id=b.id
  ) t
  where t.obra_id is not null
  group by t.obra_id
  having sum(t.valor)>0;

  return jsonb_build_object(
    'pagamento_id',v_pagamento_id,
    'diarias',v_diarias,
    'bonus_extras',v_bonus,
    'vales',v_vales,
    'bruto',v_bruto,
    'liquido',v_liquido
  );
end;
$function$;
CREATE OR REPLACE FUNCTION public.obrix_pagar_funcionario(p_funcionario_id uuid, p_data date DEFAULT CURRENT_DATE)
 RETURNS jsonb
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_empresa uuid := obrix_empresa_atual();
  v_pag uuid;
  v_diarias numeric := 0;
  v_bonus numeric := 0;
  v_vales numeric := 0;
  v_liquido numeric := 0;
  r record;
begin
  if v_empresa is null then raise exception 'Empresa não identificada'; end if;
  if not exists(select 1 from funcionarios where id=p_funcionario_id and empresa_id=v_empresa) then raise exception 'Funcionário inválido'; end if;

  select coalesce(sum(valor_total),0) into v_diarias from diarias where empresa_id=v_empresa and funcionario_id=p_funcionario_id and paga=false;
  select coalesce(sum(valor),0) into v_bonus from bonus_extras where empresa_id=v_empresa and funcionario_id=p_funcionario_id and pago=false;
  select coalesce(sum(valor),0) into v_vales from vales where empresa_id=v_empresa and funcionario_id=p_funcionario_id and quitado=false;
  v_liquido := v_diarias + v_bonus - v_vales;
  if v_diarias=0 and v_bonus=0 and v_vales=0 then raise exception 'Não há valores em aberto'; end if;
  if v_liquido < 0 then raise exception 'Líquido negativo. Revise os vales antes de pagar.'; end if;

  for r in
    with mov as (
      select obra_id, sum(valor_total) valor from diarias where empresa_id=v_empresa and funcionario_id=p_funcionario_id and paga=false group by obra_id
      union all
      select obra_id, sum(valor) from bonus_extras where empresa_id=v_empresa and funcionario_id=p_funcionario_id and pago=false group by obra_id
      union all
      select obra_id, -sum(valor) from vales where empresa_id=v_empresa and funcionario_id=p_funcionario_id and quitado=false group by obra_id
    ) select obra_id,sum(valor) valor from mov group by obra_id
  loop
    if r.valor < 0 then raise exception 'Uma obra ficou com saldo negativo. Revise os vales dessa obra.'; end if;
  end loop;

  insert into pagamentos_equipe(empresa_id,funcionario_id,valor_diarias,valor_bonus_extras,valor_vales,valor_bruto,valor_liquido,data_pagamento)
  values(v_empresa,p_funcionario_id,v_diarias,v_bonus,v_vales,v_diarias+v_bonus,v_liquido,p_data) returning id into v_pag;

  insert into pagamento_diarias(empresa_id,pagamento_id,diaria_id,obra_id,valor)
  select v_empresa,v_pag,id,obra_id,valor_total from diarias where empresa_id=v_empresa and funcionario_id=p_funcionario_id and paga=false;
  insert into pagamento_vales(empresa_id,pagamento_id,vale_id,valor)
  select v_empresa,v_pag,id,valor from vales where empresa_id=v_empresa and funcionario_id=p_funcionario_id and quitado=false;
  insert into pagamento_bonus_extras(empresa_id,pagamento_id,bonus_extra_id,valor)
  select v_empresa,v_pag,id,valor from bonus_extras where empresa_id=v_empresa and funcionario_id=p_funcionario_id and pago=false;

  with mov as (
    select obra_id, sum(valor_total) valor from diarias where empresa_id=v_empresa and funcionario_id=p_funcionario_id and paga=false group by obra_id
    union all
    select obra_id, sum(valor) from bonus_extras where empresa_id=v_empresa and funcionario_id=p_funcionario_id and pago=false group by obra_id
    union all
    select obra_id, -sum(valor) from vales where empresa_id=v_empresa and funcionario_id=p_funcionario_id and quitado=false group by obra_id
  ), tot as (select obra_id,sum(valor) valor from mov group by obra_id)
  insert into financeiro(empresa_id,obra_id,tipo,categoria,descricao,valor,data,origem,pagamento_equipe_id,status_lancamento)
  select v_empresa,obra_id,'despesa','mao_de_obra','Pagamento de equipe',valor,p_data,'pagamento_equipe',v_pag,'ativo' from tot where valor>0;

  update diarias set paga=true,pago_em=now() where empresa_id=v_empresa and funcionario_id=p_funcionario_id and paga=false;
  update vales set quitado=true,quitado_em=now() where empresa_id=v_empresa and funcionario_id=p_funcionario_id and quitado=false;
  update bonus_extras set pago=true,pago_em=now() where empresa_id=v_empresa and funcionario_id=p_funcionario_id and pago=false;
  return jsonb_build_object('pagamento_id',v_pag,'diarias',v_diarias,'bonus',v_bonus,'vales',v_vales,'liquido',v_liquido);
end;$function$;
CREATE OR REPLACE FUNCTION public.obrix_pagar_funcionario_seguro(p_funcionario_id uuid, p_data_pagamento date DEFAULT CURRENT_DATE, p_diaria_ids uuid[] DEFAULT '{}'::uuid[], p_vale_ids uuid[] DEFAULT '{}'::uuid[], p_bonus_ids uuid[] DEFAULT '{}'::uuid[])
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_empresa_id uuid := public.obrix_empresa_atual();
  v_pagamento_id uuid;
  v_nome text;
  v_qd int := coalesce(cardinality(p_diaria_ids),0);
  v_qv int := coalesce(cardinality(p_vale_ids),0);
  v_qb int := coalesce(cardinality(p_bonus_ids),0);
  v_found int;
  v_td numeric := 0;
  v_tv numeric := 0;
  v_tb numeric := 0;
  v_liq numeric := 0;
begin
  if v_empresa_id is null then raise exception 'Empresa atual não encontrada.'; end if;
  if not public.obrix_acesso_total(v_empresa_id) then raise exception 'Acesso não autorizado para esta empresa.'; end if;

  select nome into v_nome
  from public.funcionarios
  where id=p_funcionario_id and empresa_id=v_empresa_id;
  if not found then raise exception 'Funcionário não encontrado.'; end if;

  if v_qd + v_qv + v_qb = 0 then
    raise exception 'Não há valores selecionados para pagamento.';
  end if;

  if v_qd > 0 then
    perform 1 from public.diarias
    where id = any(p_diaria_ids)
      and empresa_id=v_empresa_id
      and funcionario_id=p_funcionario_id
      and paga=false
    for update;
    select count(*) into v_found from public.diarias
    where id = any(p_diaria_ids)
      and empresa_id=v_empresa_id
      and funcionario_id=p_funcionario_id
      and paga=false;
    if v_found <> v_qd then raise exception 'Uma ou mais diárias já foram pagas ou são inválidas. Atualize a equipe e tente novamente.'; end if;
  end if;

  if v_qv > 0 then
    perform 1 from public.vales
    where id = any(p_vale_ids)
      and empresa_id=v_empresa_id
      and funcionario_id=p_funcionario_id
      and quitado=false
    for update;
    select count(*) into v_found from public.vales
    where id = any(p_vale_ids)
      and empresa_id=v_empresa_id
      and funcionario_id=p_funcionario_id
      and quitado=false;
    if v_found <> v_qv then raise exception 'Um ou mais vales já foram quitados ou são inválidos. Atualize a equipe e tente novamente.'; end if;
    if exists(select 1 from public.vales where id=any(p_vale_ids) and obra_id is null) then
      raise exception 'Existe vale sem obra vinculada. Vincule a uma obra antes do pagamento.';
    end if;
  end if;

  if v_qb > 0 then
    perform 1 from public.bonus_extras
    where id = any(p_bonus_ids)
      and empresa_id=v_empresa_id
      and funcionario_id=p_funcionario_id
      and pago=false
    for update;
    select count(*) into v_found from public.bonus_extras
    where id = any(p_bonus_ids)
      and empresa_id=v_empresa_id
      and funcionario_id=p_funcionario_id
      and pago=false;
    if v_found <> v_qb then raise exception 'Um ou mais bônus/extras já foram pagos ou são inválidos. Atualize a equipe e tente novamente.'; end if;
    if exists(select 1 from public.bonus_extras where id=any(p_bonus_ids) and obra_id is null) then
      raise exception 'Existe bônus/extra sem obra vinculada. Vincule a uma obra antes do pagamento.';
    end if;
  end if;

  select coalesce(sum(valor_total),0) into v_td from public.diarias where id=any(coalesce(p_diaria_ids,'{}'::uuid[]));
  select coalesce(sum(valor),0) into v_tv from public.vales where id=any(coalesce(p_vale_ids,'{}'::uuid[]));
  select coalesce(sum(valor),0) into v_tb from public.bonus_extras where id=any(coalesce(p_bonus_ids,'{}'::uuid[]));
  v_liq := v_td + v_tb - v_tv;
  if v_liq < 0 then raise exception 'O líquido ficou negativo. Revise os vales.'; end if;

  if exists(
    with dist as (
      select obra_id, valor_total::numeric as valor from public.diarias where id=any(coalesce(p_diaria_ids,'{}'::uuid[]))
      union all
      select obra_id, valor::numeric from public.bonus_extras where id=any(coalesce(p_bonus_ids,'{}'::uuid[]))
      union all
      select obra_id, -valor::numeric from public.vales where id=any(coalesce(p_vale_ids,'{}'::uuid[]))
    )
    select 1 from dist group by obra_id having sum(valor) < 0
  ) then
    raise exception 'Existe uma obra com saldo negativo. Revise os lançamentos.';
  end if;

  insert into public.pagamentos_equipe(
    empresa_id,funcionario_id,valor_diarias,valor_bonus_extras,valor_vales,valor_bruto,valor_liquido,data_pagamento
  ) values(
    v_empresa_id,p_funcionario_id,v_td,v_tb,v_tv,v_td+v_tb,v_liq,coalesce(p_data_pagamento,current_date)
  ) returning id into v_pagamento_id;

  if v_qd > 0 then
    insert into public.pagamento_diarias(empresa_id,pagamento_id,diaria_id,obra_id,valor)
    select v_empresa_id,v_pagamento_id,id,obra_id,valor_total
    from public.diarias where id=any(p_diaria_ids);
    update public.diarias set paga=true,pago_em=now() where id=any(p_diaria_ids);
  end if;

  if v_qv > 0 then
    insert into public.pagamento_vales(empresa_id,pagamento_id,vale_id,valor)
    select v_empresa_id,v_pagamento_id,id,valor
    from public.vales where id=any(p_vale_ids);
    update public.vales set quitado=true,quitado_em=now() where id=any(p_vale_ids);
  end if;

  if v_qb > 0 then
    insert into public.pagamento_bonus_extras(empresa_id,pagamento_id,bonus_extra_id,valor)
    select v_empresa_id,v_pagamento_id,id,valor
    from public.bonus_extras where id=any(p_bonus_ids);
    update public.bonus_extras set pago=true,pago_em=now() where id=any(p_bonus_ids);
  end if;

  insert into public.financeiro(
    empresa_id,obra_id,tipo,categoria,descricao,valor,data,origem,pagamento_equipe_id,status_lancamento
  )
  with dist as (
    select obra_id, valor_total::numeric as valor from public.diarias where id=any(coalesce(p_diaria_ids,'{}'::uuid[]))
    union all
    select obra_id, valor::numeric from public.bonus_extras where id=any(coalesce(p_bonus_ids,'{}'::uuid[]))
    union all
    select obra_id, -valor::numeric from public.vales where id=any(coalesce(p_vale_ids,'{}'::uuid[]))
  )
  select v_empresa_id,obra_id,'despesa','mao_de_obra','Pagamento de equipe - '||v_nome,sum(valor),coalesce(p_data_pagamento,current_date),'pagamento_equipe',v_pagamento_id,'ativo'
  from dist
  group by obra_id
  having sum(valor) > 0;

  return v_pagamento_id;
end;
$function$;
CREATE OR REPLACE FUNCTION public.obrix_proteger_financeiro_automatico()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_origem text := coalesce(old.origem,'manual');
  v_msg text;
  v_papel text;
begin
  if v_origem = 'manual' then
    return case when TG_OP='DELETE' then old else new end;
  end if;

  if TG_OP = 'DELETE' and old.status_lancamento = 'estornado' then
    select p.papel into v_papel from public.perfis p where p.id = auth.uid() limit 1;
    if coalesce(v_papel,'') in ('proprietario','admin') then
      return old;
    end if;
  end if;

  v_msg := case v_origem
    when 'estoque' then 'Este lançamento foi gerado pelo Estoque. Faça o estorno em Estoque > Histórico.'
    when 'compra' then 'Este lançamento foi gerado por uma compra. Cancele ou estorne a compra no módulo Estoque.'
    when 'pagamento_equipe' then 'Este lançamento foi gerado por um pagamento da equipe. Faça o estorno pelo módulo Equipe.'
    else 'Este lançamento automático deve ser corrigido no módulo de origem.'
  end;

  if TG_OP = 'DELETE' then
    raise exception '%', v_msg;
  end if;

  if TG_OP = 'UPDATE' then
    if old.status_lancamento = 'ativo'
       and new.status_lancamento = 'estornado'
       and new.empresa_id is not distinct from old.empresa_id
       and new.obra_id is not distinct from old.obra_id
       and new.checklist_id is not distinct from old.checklist_id
       and new.tipo is not distinct from old.tipo
       and new.categoria is not distinct from old.categoria
       and new.descricao is not distinct from old.descricao
       and new.valor is not distinct from old.valor
       and new.data is not distinct from old.data
       and new.origem is not distinct from old.origem
       and new.pagamento_equipe_id is not distinct from old.pagamento_equipe_id
       and new.compra_id is not distinct from old.compra_id
       and new.estoque_movimentacao_id is not distinct from old.estoque_movimentacao_id then
      return new;
    end if;
    raise exception '%', v_msg;
  end if;

  return new;
end;
