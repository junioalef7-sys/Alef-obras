CREATE OR REPLACE FUNCTION public.obrix_totais_pagos_equipe_interno()
 RETURNS TABLE(funcionario_id uuid, total_pago numeric)
 LANGUAGE sql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
