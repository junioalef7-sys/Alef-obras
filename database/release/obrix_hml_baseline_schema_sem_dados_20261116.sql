CREATE OR REPLACE FUNCTION public.obrix_receber_compra(p_compra_id uuid, p_estoque_id uuid, p_nota_fiscal text DEFAULT NULL::text, p_numero_documento text DEFAULT NULL::text)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_empresa_id uuid := public.obrix_empresa_atual();
  v_compra public.compras%rowtype;
  v_subtotal numeric(14,2);
  r record;
begin
  if (select auth.uid()) is null then
    raise exception 'Usuário não autenticado.';
  end if;
  if v_empresa_id is null then
    raise exception 'Empresa atual não encontrada.';
  end if;
  if not public.obrix_acesso_total(v_empresa_id) then
    raise exception 'Acesso não autorizado para esta empresa.';
  end if;

  perform 1
    from public.estoques
   where id = p_estoque_id
     and empresa_id = v_empresa_id
     and ativo = true;
  if not found then
    raise exception 'Local de estoque ativo não encontrado.';
  end if;

  select *
    into v_compra
    from public.compras
   where id = p_compra_id
     and empresa_id = v_empresa_id
   for update;
  if not found then
    raise exception 'Compra não encontrada.';
  end if;
  if v_compra.status = 'cancelada' then
    raise exception 'Compra cancelada não pode ser recebida.';
  end if;
  if v_compra.estoque_processado then
    raise exception 'Esta compra já foi recebida no estoque.';
  end if;
  if v_compra.status not in ('rascunho','pedido','recebida') then
    raise exception 'Status da compra não permite recebimento.';
  end if;

  select coalesce(sum(valor_total),0)
    into v_subtotal
    from public.compra_itens
   where compra_id = v_compra.id
     and empresa_id = v_empresa_id;

  if not exists (
    select 1 from public.compra_itens
     where compra_id = v_compra.id
       and empresa_id = v_empresa_id
       and material_id is not null
  ) then
    raise exception 'A compra não possui itens de material para receber.';
  end if;

  update public.compras
     set subtotal = v_subtotal,
         valor_total = greatest(v_subtotal - desconto + frete + outros_custos,0),
         status = 'recebida',
         nota_fiscal = coalesce(nullif(trim(coalesce(p_nota_fiscal,'')),''), nota_fiscal),
         numero_documento = coalesce(nullif(trim(coalesce(p_numero_documento,'')),''), numero_documento),
         atualizado_em = now()
   where id = v_compra.id;

  for r in
    select material_id,
           sum(quantidade) as quantidade,
           sum(valor_total) as valor_total
      from public.compra_itens
     where compra_id = v_compra.id
       and empresa_id = v_empresa_id
       and material_id is not null
     group by material_id
  loop
    if not exists (
      select 1
        from public.estoque_movimentacoes
       where compra_id = v_compra.id
         and material_id = r.material_id
         and tipo = 'entrada'
    ) then
      insert into public.estoque_movimentacoes(
        empresa_id, material_id, estoque_destino_id, obra_id, compra_id,
        tipo, quantidade, custo_unitario, valor_total, data, documento, observacoes
      ) values (
        v_empresa_id, r.material_id, p_estoque_id, v_compra.obra_id, v_compra.id,
        'entrada', r.quantidade,
        round(r.valor_total / nullif(r.quantidade,0),2),
        r.valor_total, current_date,
        coalesce(nullif(trim(coalesce(p_nota_fiscal,'')),''), nullif(trim(coalesce(p_numero_documento,'')),''), v_compra.nota_fiscal, v_compra.numero_documento),
        'Entrada automática pelo recebimento da compra'
      );

      insert into public.estoque_saldos(empresa_id, estoque_id, material_id, quantidade)
      values(v_empresa_id, p_estoque_id, r.material_id, r.quantidade)
      on conflict (estoque_id, material_id)
      do update set quantidade = public.estoque_saldos.quantidade + excluded.quantidade,
                    atualizado_em = now();
    end if;
  end loop;

  update public.compras
     set estoque_processado = true,
         atualizado_em = now()
   where id = v_compra.id;

  return v_compra.id;
end;
