CREATE OR REPLACE FUNCTION obrix_private.notificar_mensagem_usuario_admin()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  c record;
begin
  if new.autor_tipo <> 'usuario' then
    return new;
  end if;

  select assunto, usuario_nome, usuario_email, empresa_nome
    into c
  from public.suporte_chamados
  where id = new.chamado_id;

  insert into public.notificacoes(
    usuario_id,
    empresa_id,
    tipo,
    titulo,
    mensagem,
    alvo,
    chave_unica,
    dados
  )
  select
    a.user_id,
    p.empresa_id,
    'suporte',
    'Novo contato de usuário',
    coalesce(nullif(c.usuario_nome, ''), nullif(c.usuario_email, ''), 'Usuário') ||
      ' enviou: ' || left(coalesce(c.assunto, 'Atendimento'), 120),
    'suporte_admin',
    'suporte_admin:' || a.user_id::text || ':' || new.id::text,
    jsonb_build_object(
      'chamado_id', new.chamado_id,
      'autor_id', new.usuario_id
    )
  from public.obrix_admins a
  left join public.perfis p on p.id = a.user_id
  where a.user_id <> new.usuario_id
  on conflict (chave_unica) where chave_unica is not null do nothing;

  return new;
end;
$function$;
