CREATE OR REPLACE FUNCTION public.obrix_guard_sensitive_write()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_uid uuid := (select auth.uid());
  v_papel text;
begin
  -- Rotinas internas confiáveis (service role/migrations) não possuem auth.uid().
  if v_uid is null then
    return case when TG_OP = 'DELETE' then old else new end;
  end if;

  select p.papel
    into v_papel
    from public.perfis p
   where p.id = v_uid
   limit 1;

  if coalesce(v_papel, '') not in ('proprietario', 'admin') then
    raise exception 'Operação restrita ao proprietário ou administrador da empresa.';
  end if;

  return case when TG_OP = 'DELETE' then old else new end;
end;
$function$;
