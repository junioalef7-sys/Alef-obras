      where o.empresa_id=v_empresa_id and lower(trim(o.nome))=lower(v_nome)
        and coalesce(o.data_inicio::text,'')=coalesce(r->>'data_inicio','')
      limit 1;
    if v_new_id is null then
      v_status := case lower(coalesce(r->>'status',''))
        when 'em_andamento' then 'andamento' when 'andamento' then 'andamento'
        when 'concluida' then 'concluida' when 'concluída' then 'concluida'
        when 'pausada' then 'pausada' else 'planejada' end;
      insert into public.obras(empresa_id,nome,cliente,endereco,valor_contrato,status,data_inicio,data_fim,tipo_servico,observacoes,criado_em)
      values(
        v_empresa_id,v_nome,nullif(r->>'cliente',''),nullif(r->>'endereco',''),
        greatest(coalesce(nullif(r->>'valor_contrato','')::numeric,nullif(r->>'valor','')::numeric,0),0),v_status,
        case when coalesce(r->>'data_inicio','') ~ '^\d{4}-\d{2}-\d{2}$' then (r->>'data_inicio')::date else null end,
        case when coalesce(r->>'data_fim','') ~ '^\d{4}-\d{2}-\d{2}$' then (r->>'data_fim')::date else null end,
        coalesce(nullif(r->>'tipo_servico',''),nullif(r->>'tipo_servico_personalizado','')),
        nullif(r->>'observacoes',''),
        case when coalesce(r->>'created_at','')<>'' then (r->>'created_at')::timestamptz else now() end
      ) returning id into v_new_id;
      v_new_obras:=array_append(v_new_obras,v_new_id); c_obras:=c_obras+1;
    end if;
    if coalesce(r->>'id','')<>'' then v_obra_map:=v_obra_map||jsonb_build_object(r->>'id',v_new_id::text); end if;
    v_new_id:=null;
  end loop;

  if cardinality(v_new_obras)>0 then
    delete from public.checklist_itens where empresa_id=v_empresa_id and obra_id=any(v_new_obras);
  end if;

  -- FUNCIONARIOS
  for r in select value from jsonb_array_elements(coalesce(d->'funcionarios','[]'::jsonb)) loop
    v_nome:=nullif(trim(coalesce(r->>'nome','')),'');
    if v_nome is null then c_skipped:=c_skipped+1; continue; end if;
    select f.id into v_new_id from public.funcionarios f where f.empresa_id=v_empresa_id and lower(trim(f.nome))=lower(v_nome) limit 1;
    v_obra_id:=case when coalesce(r->>'obra_id','')<>'' and (v_obra_map ? (r->>'obra_id')) then (v_obra_map->>(r->>'obra_id'))::uuid else null end;
    if v_new_id is null then
      v_tipo_pag:=case lower(coalesce(r->>'tipo_pagamento','diaria')) when 'semana' then 'semana' when 'quinzena' then 'quinzena' when 'mes' then 'mes' when 'mensal' then 'mes' else 'diaria' end;
      insert into public.funcionarios(empresa_id,obra_id,nome,cargo,tipo_pagamento,valor_diaria,salario_mensal,dia_pagamento,ativo,observacoes,criado_em)
      values(v_empresa_id,v_obra_id,v_nome,coalesce(nullif(r->>'cargo',''),nullif(r->>'funcao','')),v_tipo_pag,
        greatest(coalesce(nullif(r->>'valor_diaria','')::numeric,0),0),greatest(coalesce(nullif(r->>'salario_mensal','')::numeric,0),0),
        case when coalesce(r->>'dia_pagamento','') ~ '^\d+$' and (r->>'dia_pagamento')::int between 1 and 31 then (r->>'dia_pagamento')::int else null end,
        coalesce((r->>'ativo')::boolean,true),nullif(r->>'observacoes',''),
        case when coalesce(r->>'created_at','')<>'' then (r->>'created_at')::timestamptz else now() end)
      returning id into v_new_id;
      c_func:=c_func+1;
    end if;
    if coalesce(r->>'id','')<>'' then v_func_map:=v_func_map||jsonb_build_object(r->>'id',v_new_id::text); end if;
    v_new_id:=null;
  end loop;

  -- CHECKLIST
  for r in select value from jsonb_array_elements(coalesce(d->'checklist','[]'::jsonb)) loop
    if not (v_obra_map ? coalesce(r->>'obra_id','')) then c_skipped:=c_skipped+1; continue; end if;
    v_obra_id:=(v_obra_map->>(r->>'obra_id'))::uuid;
    v_nome:=coalesce(nullif(trim(r->>'tarefa'),''),nullif(trim(r->>'nome'),''));
    if v_nome is null then c_skipped:=c_skipped+1; continue; end if;
    v_ord:=v_ord+1;
    select id into v_new_id from public.checklist_itens where empresa_id=v_empresa_id and obra_id=v_obra_id and lower(trim(nome))=lower(v_nome) limit 1;
    if v_new_id is null then
      insert into public.checklist_itens(empresa_id,obra_id,nome,progresso,ordem,concluido,criado_em)
      values(v_empresa_id,v_obra_id,v_nome,least(100,greatest(0,coalesce(nullif(r->>'progresso','')::int,0))),v_ord,
        coalesce((r->>'concluida')::boolean,false) or coalesce(nullif(r->>'progresso','')::int,0)>=100,
        case when coalesce(r->>'created_at','')<>'' then (r->>'created_at')::timestamptz else now() end);
      c_check:=c_check+1;
    else
      update public.checklist_itens set progresso=least(100,greatest(0,coalesce(nullif(r->>'progresso','')::int,0))),concluido=coalesce((r->>'concluida')::boolean,false) or coalesce(nullif(r->>'progresso','')::int,0)>=100 where id=v_new_id;
    end if;
    v_new_id:=null;
  end loop;

  -- DIARIAS
  for r in select value from jsonb_array_elements(coalesce(d->'diarias','[]'::jsonb)) loop
    if not (v_obra_map ? coalesce(r->>'obra_id','')) or not (v_func_map ? coalesce(r->>'funcionario_id','')) then c_skipped:=c_skipped+1; continue; end if;
    v_obra_id:=(v_obra_map->>(r->>'obra_id'))::uuid; v_func_id:=(v_func_map->>(r->>'funcionario_id'))::uuid;
    v_qtd:=coalesce(nullif(r->>'qtd','')::numeric,nullif(r->>'quantidade','')::numeric,1); if v_qtd<=0.5 then v_qtd:=0.5; else v_qtd:=1; end if;
    v_unit:=greatest(coalesce(nullif(r->>'valor_diaria','')::numeric,nullif(r->>'valor_unitario','')::numeric,nullif(r->>'valor','')::numeric,0),0);
    v_total:=greatest(coalesce(nullif(r->>'valor_total','')::numeric,v_unit*v_qtd,0),0);
    v_paga:=lower(coalesce(r->>'status','')) in ('pago','paga','quitado') or coalesce(nullif(r->>'qtd_paga','')::numeric,0)>=v_qtd or coalesce(nullif(r->>'valor_baixado','')::numeric,0)>=v_total;
    if not exists(select 1 from public.diarias x where x.empresa_id=v_empresa_id and x.funcionario_id=v_func_id and x.obra_id=v_obra_id and x.data=coalesce(nullif(r->>'data','')::date,current_date) and x.quantidade=v_qtd and x.valor_total=v_total and coalesce(x.observacoes,'')=coalesce(r->>'observacao',r->>'observacoes','')) then
      insert into public.diarias(empresa_id,funcionario_id,obra_id,data,quantidade,valor_unitario,valor_total,paga,pago_em,observacoes,criado_em)
      values(v_empresa_id,v_func_id,v_obra_id,coalesce(nullif(r->>'data','')::date,current_date),v_qtd,v_unit,v_total,v_paga,
        case when coalesce(r->>'pago_em','')<>'' then (r->>'pago_em')::timestamptz else null end,
        coalesce(nullif(r->>'observacao',''),nullif(r->>'observacoes','')),
        case when coalesce(r->>'created_at','')<>'' then (r->>'created_at')::timestamptz else now() end);
      c_diarias:=c_diarias+1;
    end if;
  end loop;

  -- FALTAS
  for r in select value from jsonb_array_elements(coalesce(d->'faltas','[]'::jsonb)) loop
    if not (v_func_map ? coalesce(r->>'funcionario_id','')) then c_skipped:=c_skipped+1; continue; end if;
    v_func_id:=(v_func_map->>(r->>'funcionario_id'))::uuid;
    v_obra_id:=case when v_obra_map ? coalesce(r->>'obra_id','') then (v_obra_map->>(r->>'obra_id'))::uuid else null end;
    if not exists(select 1 from public.faltas x where x.empresa_id=v_empresa_id and x.funcionario_id=v_func_id and x.data=coalesce(nullif(r->>'data','')::date,current_date) and x.obra_id is not distinct from v_obra_id) then
      insert into public.faltas(empresa_id,funcionario_id,obra_id,data,justificada,motivo,observacoes,criado_em)
      values(v_empresa_id,v_func_id,v_obra_id,coalesce(nullif(r->>'data','')::date,current_date),lower(coalesce(r->>'tipo','')) in ('justificada','atestado'),nullif(r->>'tipo',''),coalesce(nullif(r->>'observacao',''),nullif(r->>'observacoes','')),case when coalesce(r->>'created_at','')<>'' then (r->>'created_at')::timestamptz else now() end);
      c_faltas:=c_faltas+1;
    end if;
  end loop;

  -- GASTOS / DESPESAS + VALES
  for r in select value from jsonb_array_elements(coalesce(d->'gastos','[]'::jsonb)) loop
    if not (v_obra_map ? coalesce(r->>'obra_id','')) then c_skipped:=c_skipped+1; continue; end if;
    v_obra_id:=(v_obra_map->>(r->>'obra_id'))::uuid; v_valor:=coalesce(nullif(r->>'valor','')::numeric,0); if v_valor<=0 then c_skipped:=c_skipped+1; continue; end if;
    v_desc:=coalesce(nullif(r->>'descricao',''),'Despesa importada do EDIFIQ');
    v_txt:=lower(coalesce(r->>'categoria','')||' '||coalesce(r->>'subcategoria','')||' '||v_desc);
    v_cat:=case when v_txt like '%material%' then 'material' when v_txt like '%mão de obra%' or v_txt like '%mao de obra%' then 'mao_de_obra' when v_txt like '%serviço terceirizado%' or v_txt like '%servico terceirizado%' then 'servico_terceirizado' when v_txt like '%ferrament%' then 'ferramentas_equipamentos' when v_txt like '%locação%' or v_txt like '%locacao%' then 'locacao' when v_txt like '%transporte%' then 'transporte' when v_txt like '%combust%' then 'combustivel' else 'outros' end;
    v_marker:='[EDIFIQ:'||coalesce(r->>'id',md5(coalesce(r::text,'')))||']';
    if not exists(select 1 from public.financeiro x where x.empresa_id=v_empresa_id and coalesce(x.observacoes,'') like '%'||v_marker||'%') then
      insert into public.financeiro(empresa_id,obra_id,tipo,categoria,descricao,valor,data,origem,observacoes,status_lancamento,criado_em)
      values(v_empresa_id,v_obra_id,'despesa',v_cat,v_desc,v_valor,coalesce(nullif(r->>'data','')::date,current_date),'manual',concat_ws(' · ',nullif(r->>'fornecedor',''),nullif(r->>'observacao',''),v_marker),'ativo',case when coalesce(r->>'created_at','')<>'' then (r->>'created_at')::timestamptz else now() end);
      c_fin_desp:=c_fin_desp+1;
    end if;

    if v_txt like '%adiantamento%' then
      v_provider:=trim(coalesce(r->>'fornecedor',''));
      frow:=null;
      if v_provider<>'' then
        select z.value into frow from jsonb_array_elements(coalesce(d->'funcionarios','[]'::jsonb)) z(value)
        where lower(trim(z.value->>'nome'))=lower(v_provider)
           or lower(trim(z.value->>'nome')) like lower(v_provider)||'%'
           or lower(v_provider) like lower(trim(z.value->>'nome'))||'%'
        limit 1;
      end if;
      if frow is not null and (v_func_map ? coalesce(frow->>'id','')) then
        v_func_id:=(v_func_map->>(frow->>'id'))::uuid;
        v_aplicado:=coalesce(nullif(p_backup->'adiantamentosAplicados'->>(r->>'id'),'')::numeric,0);
        if not exists(select 1 from public.vales x where x.empresa_id=v_empresa_id and x.funcionario_id=v_func_id and x.obra_id is not distinct from v_obra_id and x.data=coalesce(nullif(r->>'data','')::date,current_date) and x.valor=v_valor) then
          insert into public.vales(empresa_id,funcionario_id,obra_id,valor,data,quitado,quitado_em,observacoes,criado_em)
          values(v_empresa_id,v_func_id,v_obra_id,v_valor,coalesce(nullif(r->>'data','')::date,current_date),v_aplicado>=v_valor,case when v_aplicado>=v_valor then coalesce(nullif(r->>'data','')::date,current_date)::timestamptz else null end,'Importado do EDIFIQ: '||v_desc,case when coalesce(r->>'created_at','')<>'' then (r->>'created_at')::timestamptz else now() end);
          c_vales:=c_vales+1;
        end if;
      end if;
    end if;
  end loop;

  -- RECEBIMENTOS
  for r in select value from jsonb_array_elements(coalesce(d->'pagamentos','[]'::jsonb)) loop
    if not (v_obra_map ? coalesce(r->>'obra_id','')) then c_skipped:=c_skipped+1; continue; end if;
    v_obra_id:=(v_obra_map->>(r->>'obra_id'))::uuid; v_valor:=coalesce(nullif(r->>'valor','')::numeric,0); if v_valor<=0 then c_skipped:=c_skipped+1; continue; end if;
    v_desc:=coalesce(nullif(r->>'descricao',''),'Recebimento importado do EDIFIQ'); v_marker:='[EDIFIQ:'||coalesce(r->>'id',md5(coalesce(r::text,'')))||']';
    if not exists(select 1 from public.financeiro x where x.empresa_id=v_empresa_id and coalesce(x.observacoes,'') like '%'||v_marker||'%') then
      insert into public.financeiro(empresa_id,obra_id,tipo,categoria,descricao,valor,data,origem,observacoes,status_lancamento,criado_em)
      values(v_empresa_id,v_obra_id,'receita','entrada',v_desc,v_valor,coalesce(nullif(r->>'data','')::date,current_date),'manual',concat_ws(' · ',nullif(r->>'fornecedor',''),nullif(r->>'observacao',''),v_marker),'ativo',case when coalesce(r->>'created_at','')<>'' then (r->>'created_at')::timestamptz else now() end);
      c_fin_rec:=c_fin_rec+1;
    end if;
  end loop;

  -- DIARIO DE OBRA
  for r in select value from jsonb_array_elements(coalesce(d->'diario','[]'::jsonb)) loop
    if not (v_obra_map ? coalesce(r->>'obra_id','')) then c_skipped:=c_skipped+1; continue; end if;
    v_obra_id:=(v_obra_map->>(r->>'obra_id'))::uuid;
    if not exists(select 1 from public.diarios_obra x where x.empresa_id=v_empresa_id and x.obra_id=v_obra_id and x.data=coalesce(nullif(r->>'data','')::date,current_date)) then
      insert into public.diarios_obra(empresa_id,obra_id,data,clima,servicos_executados,observacoes,status,criado_em)
      values(v_empresa_id,v_obra_id,coalesce(nullif(r->>'data','')::date,current_date),nullif(r->>'clima',''),nullif(r->>'atividades',''),concat_ws(' · ',nullif(r->>'observacoes',''),case when coalesce(r->>'horas','')<>'' then 'Horas: '||(r->>'horas') else null end),'finalizado',case when coalesce(r->>'created_at','')<>'' then (r->>'created_at')::timestamptz else now() end)
      returning id into v_new_id;
      c_diario:=c_diario+1;
      if jsonb_typeof(r->'equipe')='array' then
        for frow in select value from jsonb_array_elements(r->'equipe') loop
          if v_func_map ? trim(both '"' from frow::text) then
            begin
              insert into public.diario_equipe(empresa_id,diario_id,funcionario_id) values(v_empresa_id,v_new_id,(v_func_map->>trim(both '"' from frow::text))::uuid);
            exception when unique_violation then null; end;
          end if;
        end loop;
      end if;
    end if;
  end loop;

  -- SERVICOS ADICIONAIS
  if jsonb_typeof(p_backup->'servicosAdicionais')='object' then
    for sx_key,sx_arr in select key,value from jsonb_each(p_backup->'servicosAdicionais') loop
      if not (v_obra_map ? sx_key) or jsonb_typeof(sx_arr)<>'array' then continue; end if;
      v_obra_id:=(v_obra_map->>sx_key)::uuid;
      for sx in select value from jsonb_array_elements(sx_arr) loop
        v_valor:=coalesce(nullif(sx->>'valor','')::numeric,0); v_desc:=coalesce(nullif(sx->>'descricao',''),nullif(sx->>'nome',''),'Serviço extra importado');
        if v_valor>=0 and not exists(select 1 from public.servicos_extras x where x.empresa_id=v_empresa_id and x.obra_id=v_obra_id and lower(x.descricao)=lower(v_desc) and x.valor=v_valor) then
          insert into public.servicos_extras(empresa_id,obra_id,descricao,valor,data,observacoes)
          values(v_empresa_id,v_obra_id,v_desc,v_valor,case when coalesce(sx->>'data','') ~ '^\d{4}-\d{2}-\d{2}$' then (sx->>'data')::date else current_date end,'Importado do EDIFIQ'); c_extras:=c_extras+1;
        end if;
      end loop;
    end loop;
  end if;

  return jsonb_build_object('ok',true,'obras',c_obras,'funcionarios',c_func,'checklist',c_check,'diarias',c_diarias,'faltas',c_faltas,'despesas',c_fin_desp,'receitas',c_fin_rec,'vales',c_vales,'diario',c_diario,'servicos_extras',c_extras,'ignorados',c_skipped);
end;
