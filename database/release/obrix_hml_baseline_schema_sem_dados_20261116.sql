CREATE OR REPLACE FUNCTION public.obrix_restaurar_backup_edifiq_interno(p_backup jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_uid uuid := auth.uid();
  v_empresa_id uuid;
  d jsonb;
  r jsonb;
  frow jsonb;
  sx_key text;
  sx_arr jsonb;
  sx jsonb;
  v_obra_map jsonb := '{}'::jsonb;
  v_func_map jsonb := '{}'::jsonb;
  v_new_obras uuid[] := array[]::uuid[];
  v_new_id uuid;
  v_obra_id uuid;
  v_func_id uuid;
  v_nome text;
  v_desc text;
  v_txt text;
  v_cat text;
  v_provider text;
  v_marker text;
  v_tipo_pag text;
  v_status text;
  v_qtd numeric;
  v_unit numeric;
  v_total numeric;
  v_valor numeric;
  v_aplicado numeric;
  v_paga boolean;
  v_ord integer := 0;
  c_obras int:=0; c_func int:=0; c_check int:=0; c_diarias int:=0; c_faltas int:=0;
  c_fin_desp int:=0; c_fin_rec int:=0; c_vales int:=0; c_diario int:=0; c_extras int:=0; c_skipped int:=0;
begin
  if v_uid is null then raise exception 'Sessao nao encontrada.'; end if;
  select empresa_id into v_empresa_id from public.perfis where id=v_uid limit 1;
  if v_empresa_id is null then raise exception 'Perfil OBRIX nao encontrado.'; end if;
  if p_backup is null or jsonb_typeof(p_backup) <> 'object' then raise exception 'Backup invalido.'; end if;

  d := case
    when jsonb_typeof(p_backup->'data')='object' then p_backup->'data'
    when jsonb_typeof(p_backup->'dados')='object' then p_backup->'dados'
    else p_backup
  end;
  if jsonb_typeof(d) <> 'object' then raise exception 'Backup sem dados.'; end if;
  if not (d ? 'obras') then raise exception 'Backup EDIFIQ sem obras.'; end if;

  perform set_config('obrix.restore','on',true);

  -- OBRAS
  for r in select value from jsonb_array_elements(coalesce(d->'obras','[]'::jsonb)) loop
    v_nome := nullif(trim(coalesce(r->>'nome','')),'');
    if v_nome is null then c_skipped:=c_skipped+1; continue; end if;
