CREATE OR REPLACE FUNCTION public.obrix_transferir_estoque(p_material_id uuid, p_estoque_origem_id uuid, p_estoque_destino_id uuid, p_quantidade numeric, p_data date DEFAULT CURRENT_DATE, p_documento text DEFAULT NULL::text, p_observacoes text DEFAULT NULL::text)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_empresa_id uuid := public.obrix_empresa_atual();
  v_obra_destino_id uuid;
  v_movimento_id uuid;
  v_saldo numeric;
  v_custo numeric;
begin
  if (select auth.uid()) is null then
    raise exception 'Usuário não autenticado.';
  end if;
  if v_empresa_id is null then
    raise exception 'Empresa atual não encontrada.';
  end if;
  if not public.obrix_acesso_total(v_empresa_id) then
    raise exception 'Acesso não autorizado para esta empresa.';
  end if;
  if p_quantidade is null or p_quantidade <= 0 then
    raise exception 'Quantidade deve ser maior que zero.';
  end if;
  if p_estoque_origem_id = p_estoque_destino_id then
    raise exception 'O estoque de origem e o de destino devem ser diferentes.';
  end if;

  perform 1
    from public.materiais
   where id = p_material_id
     and empresa_id = v_empresa_id
     and ativo = true;
  if not found then
    raise exception 'Material ativo não encontrado.';
  end if;

  perform 1
    from public.estoques
   where id = p_estoque_origem_id
     and empresa_id = v_empresa_id
     and ativo = true;
  if not found then
    raise exception 'Estoque de origem ativo não encontrado.';
  end if;

  select obra_id
    into v_obra_destino_id
    from public.estoques
   where id = p_estoque_destino_id
     and empresa_id = v_empresa_id
     and ativo = true;
  if not found then
    raise exception 'Estoque de destino ativo não encontrado.';
  end if;

  select quantidade
    into v_saldo
    from public.estoque_saldos
   where empresa_id = v_empresa_id
     and estoque_id = p_estoque_origem_id
     and material_id = p_material_id
   for update;

  if v_saldo is null then
    raise exception 'Saldo não encontrado para este material no estoque de origem.';
  end if;
  if v_saldo < p_quantidade then
    raise exception 'Saldo insuficiente. Disponível: %.', v_saldo;
  end if;

  select coalesce(custo_medio,0)
    into v_custo
    from public.materiais
   where id = p_material_id
     and empresa_id = v_empresa_id;

  update public.estoque_saldos
     set quantidade = quantidade - p_quantidade,
         atualizado_em = now()
   where empresa_id = v_empresa_id
     and estoque_id = p_estoque_origem_id
     and material_id = p_material_id;

  insert into public.estoque_saldos(empresa_id, estoque_id, material_id, quantidade, atualizado_em)
  values(v_empresa_id, p_estoque_destino_id, p_material_id, p_quantidade, now())
  on conflict (estoque_id, material_id)
  do update set quantidade = public.estoque_saldos.quantidade + excluded.quantidade,
                atualizado_em = now();

  insert into public.estoque_movimentacoes(
    empresa_id, material_id, estoque_origem_id, estoque_destino_id, obra_id, tipo,
    quantidade, custo_unitario, valor_total, data, documento, observacoes
  ) values (
    v_empresa_id, p_material_id, p_estoque_origem_id, p_estoque_destino_id, v_obra_destino_id, 'transferencia',
    p_quantidade, v_custo, p_quantidade * v_custo,
    coalesce(p_data,current_date), nullif(trim(p_documento),''), nullif(trim(p_observacoes),'')
  ) returning id into v_movimento_id;

  return v_movimento_id;
end;
$function$;
CREATE OR REPLACE FUNCTION public.obrix_validar_quantidade_discreta_movimento()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare
  v_unidade text;
begin
  select lower(coalesce(unidade,''))
    into v_unidade
    from public.materiais
   where id = new.material_id
     and empresa_id = new.empresa_id;

  if v_unidade in ('un','saco','cx','caixa')
     and new.quantidade <> trunc(new.quantidade) then
    raise exception 'Este material usa unidade inteira (%). Informe uma quantidade sem decimais.', v_unidade;
  end if;

  return new;
end;
$function$;
CREATE OR REPLACE FUNCTION public.processar_compra(p_compra_id uuid)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_empresa_id uuid;
  v_compra public.compras%rowtype;
  v_estoque_id uuid;
  v_subtotal numeric(14,2);
  r record;
begin

  -- Empresa do usuário conectado
  select empresa_id
  into v_empresa_id
  from public.perfis
  where id = auth.uid();

  if v_empresa_id is null then
    raise exception 'Usuário sem empresa vinculada.';
  end if;


  -- Bloqueia a compra durante o processamento
  select *
  into v_compra
  from public.compras
  where id = p_compra_id
    and empresa_id = v_empresa_id
  for update;

  if not found then
    raise exception 'Compra não encontrada ou sem permissão.';
  end if;


  -- Recalcula o subtotal pelos itens
  select coalesce(sum(valor_total), 0)
  into v_subtotal
  from public.compra_itens
  where compra_id = v_compra.id
    and empresa_id = v_empresa_id;


  update public.compras
  set
    subtotal = v_subtotal,

    valor_total = greatest(
      v_subtotal
      - desconto
      + frete
      + outros_custos,
      0
    ),

    atualizado_em = now()

  where id = v_compra.id
  returning *
  into v_compra;


  -- Somente compras recebidas ou pagas
  if v_compra.status not in ('recebida', 'paga') then
    raise exception
      'A compra precisa estar Recebida ou Paga para ser processada.';
  end if;


  -- ===================================================
  -- ESTOQUE
  -- ===================================================

  if not v_compra.estoque_processado then

    -- Compra destinada a uma obra
    if v_compra.obra_id is not null then

      select id
      into v_estoque_id
      from public.estoques
      where empresa_id = v_empresa_id
        and obra_id = v_compra.obra_id
        and tipo = 'obra'
        and ativo = true
      limit 1;


      -- Cria o estoque da obra se ainda não existir
      if v_estoque_id is null then

        insert into public.estoques (
          empresa_id,
          obra_id,
          nome,
          tipo
        )
        values (
          v_empresa_id,
          v_compra.obra_id,
          'Estoque da Obra',
          'obra'
        )
        returning id into v_estoque_id;

      end if;


    -- Compra para estoque geral
    else

      select id
      into v_estoque_id
      from public.estoques
      where empresa_id = v_empresa_id
        and tipo = 'geral'
        and ativo = true
      limit 1;


      if v_estoque_id is null then

        insert into public.estoques (
          empresa_id,
          nome,
          tipo
        )
        values (
          v_empresa_id,
          'Estoque Geral',
          'geral'
        )
        returning id into v_estoque_id;

      end if;

    end if;


    -- Agrupa materiais iguais da mesma compra
    for r in

      select
        material_id,
        sum(quantidade) as quantidade,
        sum(valor_total) as valor_total

      from public.compra_itens

      where compra_id = v_compra.id
        and empresa_id = v_empresa_id
        and material_id is not null

      group by material_id

    loop

      -- Só processa se ainda não houver movimento
      if not exists (
        select 1
        from public.estoque_movimentacoes
        where compra_id = v_compra.id
          and material_id = r.material_id
          and tipo = 'entrada'
      ) then

        insert into public.estoque_movimentacoes (
          empresa_id,
          material_id,
          estoque_destino_id,
          obra_id,
          compra_id,
          tipo,
          quantidade,
          custo_unitario,
          valor_total,
          data,
          documento,
          observacoes
        )
        values (
          v_empresa_id,
          r.material_id,
          v_estoque_id,
          v_compra.obra_id,
          v_compra.id,
          'entrada',
          r.quantidade,

          round(
            r.valor_total / nullif(r.quantidade, 0),
            2
          ),

          r.valor_total,
          v_compra.data_compra,

          coalesce(
            v_compra.nota_fiscal,
            v_compra.numero_documento
          ),

          'Entrada automática pela compra'
        );


        -- Atualiza o saldo real
        insert into public.estoque_saldos (
          empresa_id,
          estoque_id,
          material_id,
          quantidade
        )
        values (
          v_empresa_id,
          v_estoque_id,
          r.material_id,
          r.quantidade
        )

        on conflict (estoque_id, material_id)

        do update set
          quantidade =
            public.estoque_saldos.quantidade
            + excluded.quantidade,

          atualizado_em = now();

      end if;

    end loop;


    update public.compras
    set estoque_processado = true,
        atualizado_em = now()
    where id = v_compra.id;

  end if;


  -- ===================================================
  -- FINANCEIRO
  -- Só lança quando estiver PAGA
  -- ===================================================

  if v_compra.status = 'paga'
     and not v_compra.financeiro_processado then

    if not exists (
      select 1
      from public.financeiro
      where compra_id = v_compra.id
    ) then

      insert into public.financeiro (
        empresa_id,
        obra_id,
        tipo,
        categoria,
        descricao,
        valor,
        data,
        origem,
        compra_id
      )
      values (
        v_empresa_id,
        v_compra.obra_id,
        'despesa',
        'material',

        'Compra #' ||
        v_compra.numero_pedido::text,

        v_compra.valor_total,
        v_compra.data_compra,
        'compra',
        v_compra.id
      );

    end if;


    update public.compras
    set financeiro_processado = true,
        atualizado_em = now()
    where id = v_compra.id;

  end if;

end;
$function$;
CREATE OR REPLACE FUNCTION public.rls_auto_enable()
 RETURNS event_trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog'
AS $function$
DECLARE
  cmd record;
  tbl name;
BEGIN
  FOR cmd IN
    SELECT *
    FROM pg_event_trigger_ddl_commands()
    WHERE command_tag IN ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
      AND object_type IN ('table','partitioned table')
  LOOP
     IF cmd.schema_name IS NOT NULL AND cmd.schema_name IN ('public') AND cmd.schema_name NOT IN ('pg_catalog','information_schema') AND cmd.schema_name NOT LIKE 'pg_toast%' AND cmd.schema_name NOT LIKE 'pg_temp%' THEN
      BEGIN
        SELECT c.relname INTO tbl FROM pg_catalog.pg_class c WHERE c.oid = cmd.objid;
        EXECUTE format('alter table if exists %I.%I enable row level security', cmd.schema_name, tbl);
        RAISE LOG 'rls_auto_enable: enabled RLS on %', cmd.object_identity;
      EXCEPTION
        WHEN OTHERS THEN
          RAISE LOG 'rls_auto_enable: failed to enable RLS on %', cmd.object_identity;
      END;
     ELSE
        RAISE LOG 'rls_auto_enable: skip % (either system schema or not in enforced list: %.)', cmd.object_identity, cmd.schema_name;
     END IF;
  END LOOP;
END;
$function$;
