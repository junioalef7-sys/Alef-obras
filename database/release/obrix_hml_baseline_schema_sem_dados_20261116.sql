CREATE OR REPLACE FUNCTION public.obrix_sync_orcamento_checklist(p_orcamento_id uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  v_orc public.orcamentos%rowtype;
  v_item public.orcamento_itens%rowtype;
  v_marker text;
  v_check_id uuid;
begin
  select * into v_orc
  from public.orcamentos
  where id = p_orcamento_id
    and status = 'aprovado'
    and obra_id is not null;

  if not found then
    return;
  end if;

  for v_item in
    select * from public.orcamento_itens
    where orcamento_id = p_orcamento_id
    order by ordem, criado_em
  loop
    v_marker := '[OBRIX_ORC:' || p_orcamento_id::text || ':ITEM:' || v_item.ordem::text || ']';
    v_check_id := null;

    select id into v_check_id
    from public.checklist_itens
    where empresa_id = v_orc.empresa_id
      and obra_id = v_orc.obra_id
      and observacoes like v_marker || '%'
    limit 1;

    if v_check_id is null then
      insert into public.checklist_itens (
        empresa_id, obra_id, nome, progresso, ordem, concluido, observacoes, valor
      ) values (
        v_orc.empresa_id,
        v_orc.obra_id,
        v_item.descricao,
        0,
        v_item.ordem,
        false,
        concat(v_marker, case when v_item.observacoes is not null then E'\n' || v_item.observacoes else '' end),
        coalesce(v_item.valor_total, round(v_item.quantidade * v_item.valor_unitario,2), 0)
      );
    else
      update public.checklist_itens
      set nome = v_item.descricao,
          valor = coalesce(v_item.valor_total, round(v_item.quantidade * v_item.valor_unitario,2), 0),
          ordem = v_item.ordem,
          observacoes = concat(v_marker, case when v_item.observacoes is not null then E'\n' || v_item.observacoes else '' end),
          atualizado_em = now()
      where id = v_check_id;
    end if;
  end loop;
end;
$function$;
CREATE OR REPLACE FUNCTION public.obrix_totais_pagos_equipe()
 RETURNS TABLE(funcionario_id uuid, total_pago numeric)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_empresa_id uuid := public.obrix_empresa_atual();
begin
  if v_empresa_id is null or not public.obrix_acesso_total(v_empresa_id) then
    return;
  end if;
