CREATE OR REPLACE FUNCTION public.obrix_criar_reposicao_estoque(p_material_id uuid, p_quantidade numeric, p_fornecedor_id uuid DEFAULT NULL::uuid, p_fornecedor_nome text DEFAULT NULL::text, p_valor_unitario numeric DEFAULT 0, p_observacoes text DEFAULT NULL::text)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_empresa_id uuid := public.obrix_empresa_atual();
  v_fornecedor_id uuid;
  v_compra_id uuid;
  v_numero bigint;
  v_material_nome text;
  v_unidade text;
  v_total numeric;
begin
  if (select auth.uid()) is null then
    raise exception 'Usuário não autenticado.';
  end if;
  if v_empresa_id is null then
    raise exception 'Empresa atual não encontrada.';
  end if;
  if not public.obrix_acesso_total(v_empresa_id) then
    raise exception 'Acesso não autorizado para esta empresa.';
  end if;
  if p_quantidade is null or p_quantidade <= 0 then
    raise exception 'Quantidade deve ser maior que zero.';
  end if;
  if coalesce(p_valor_unitario,0) < 0 then
    raise exception 'Valor unitário inválido.';
  end if;

  select nome, unidade
    into v_material_nome, v_unidade
    from public.materiais
   where id = p_material_id
     and empresa_id = v_empresa_id
     and ativo = true;
  if not found then
    raise exception 'Material ativo não encontrado.';
  end if;

  if lower(coalesce(v_unidade,'')) in ('un','unidade','unidades','saco','sacos','cx','caixa','caixas')
     and p_quantidade <> trunc(p_quantidade) then
    raise exception 'Este material só aceita quantidade inteira.';
  end if;

  if p_fornecedor_id is not null then
    select id into v_fornecedor_id
      from public.fornecedores
     where id = p_fornecedor_id
       and empresa_id = v_empresa_id
       and ativo = true;
    if not found then
      raise exception 'Fornecedor ativo não encontrado.';
    end if;
  else
    if nullif(trim(coalesce(p_fornecedor_nome,'')),'') is null then
      raise exception 'Informe o fornecedor.';
    end if;
    select id into v_fornecedor_id
      from public.fornecedores
     where empresa_id = v_empresa_id
       and ativo = true
       and lower(nome) = lower(trim(p_fornecedor_nome))
     limit 1;
    if v_fornecedor_id is null then
      insert into public.fornecedores(empresa_id,nome,tipo,ativo)
      values(v_empresa_id,trim(p_fornecedor_nome),'empresa',true)
      returning id into v_fornecedor_id;
    end if;
  end if;

  perform pg_advisory_xact_lock(hashtext(v_empresa_id::text));
  select coalesce(max(numero_pedido),0)+1
    into v_numero
    from public.compras
   where empresa_id = v_empresa_id;

  v_total := round(p_quantidade * coalesce(p_valor_unitario,0),2);

  insert into public.compras(
    empresa_id, fornecedor_id, numero_pedido, data_compra, status,
    subtotal, desconto, frete, outros_custos, valor_total,
    estoque_processado, financeiro_processado, observacoes
  ) values (
    v_empresa_id, v_fornecedor_id, v_numero, current_date, 'rascunho',
    v_total, 0, 0, 0, v_total,
    false, false, nullif(trim(coalesce(p_observacoes,'')),'')
  ) returning id into v_compra_id;

  insert into public.compra_itens(
    empresa_id, compra_id, material_id, descricao, quantidade,
    unidade, valor_unitario, observacoes
  ) values (
    v_empresa_id, v_compra_id, p_material_id, v_material_nome, p_quantidade,
    coalesce(v_unidade,'un'), coalesce(p_valor_unitario,0),
    'Reposição gerada pelo alerta de estoque mínimo'
  );

  return v_compra_id;
end;
$function$;
