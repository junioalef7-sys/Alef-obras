CREATE OR REPLACE FUNCTION public.obrix_estornar_pagamento_equipe(p_pagamento_id uuid, p_motivo text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_empresa_id uuid := public.obrix_empresa_atual();
  v_pag public.pagamentos_equipe%rowtype;
  v_diarias integer := 0;
  v_vales integer := 0;
  v_bonus integer := 0;
  v_financeiro integer := 0;
begin
  if (select auth.uid()) is null then
    raise exception 'Usuário não autenticado.';
  end if;
  if v_empresa_id is null or not public.obrix_acesso_total(v_empresa_id) then
    raise exception 'Acesso não autorizado para estorno de pagamento da equipe.';
  end if;

  select * into v_pag
  from public.pagamentos_equipe
  where id = p_pagamento_id
    and empresa_id = v_empresa_id
  for update;

  if not found then
    raise exception 'Pagamento da equipe não encontrado.';
  end if;

  if v_pag.estornado_em is not null then
    return jsonb_build_object(
      'ok', true,
      'ja_estornado', true,
      'pagamento_id', v_pag.id,
      'estornado_em', v_pag.estornado_em
    );
  end if;

  update public.diarias d
     set paga = false,
         pago_em = null
   where d.empresa_id = v_empresa_id
     and exists (
       select 1
       from public.pagamento_diarias pd
       where pd.pagamento_id = v_pag.id
         and pd.empresa_id = v_empresa_id
         and pd.diaria_id = d.id
         and pd.ativo = true
     );
  get diagnostics v_diarias = row_count;

  update public.vales v
     set quitado = false,
         quitado_em = null
   where v.empresa_id = v_empresa_id
     and exists (
       select 1
       from public.pagamento_vales pv
       where pv.pagamento_id = v_pag.id
         and pv.empresa_id = v_empresa_id
         and pv.vale_id = v.id
         and pv.ativo = true
     );
  get diagnostics v_vales = row_count;

  update public.bonus_extras b
     set pago = false,
         pago_em = null
   where b.empresa_id = v_empresa_id
     and exists (
       select 1
       from public.pagamento_bonus_extras pb
       where pb.pagamento_id = v_pag.id
         and pb.empresa_id = v_empresa_id
         and pb.bonus_extra_id = b.id
         and pb.ativo = true
     );
  get diagnostics v_bonus = row_count;

  update public.pagamento_diarias
     set ativo = false
   where pagamento_id = v_pag.id
     and empresa_id = v_empresa_id
     and ativo = true;

  update public.pagamento_vales
     set ativo = false
   where pagamento_id = v_pag.id
     and empresa_id = v_empresa_id
     and ativo = true;

  update public.pagamento_bonus_extras
     set ativo = false
   where pagamento_id = v_pag.id
     and empresa_id = v_empresa_id
     and ativo = true;

  update public.financeiro
     set status_lancamento = 'estornado',
         atualizado_em = now(),
         observacoes = concat_ws(' | ', nullif(observacoes,''), 'Estornado pelo pagamento da equipe')
   where empresa_id = v_empresa_id
     and pagamento_equipe_id = v_pag.id
     and origem = 'pagamento_equipe'
     and status_lancamento = 'ativo';
  get diagnostics v_financeiro = row_count;

  update public.pagamentos_equipe
     set estornado_em = now(),
         motivo_estorno = nullif(trim(coalesce(p_motivo,'')),'')
   where id = v_pag.id;

  return jsonb_build_object(
    'ok', true,
    'ja_estornado', false,
    'pagamento_id', v_pag.id,
    'diarias_reabertas', v_diarias,
    'vales_reabertos', v_vales,
    'bonus_reabertos', v_bonus,
    'financeiro_estornado', v_financeiro
  );
end;
$function$;
CREATE OR REPLACE FUNCTION public.obrix_estornar_saida_estoque(p_movimento_id uuid)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_empresa_id uuid := public.obrix_empresa_atual();
